/**
 * Récupère le tarif formaté d'un sous-service
 */
export function getTarifLabel(subService: typeof SUB_SERVICES[number]): string {
  if (subService.basePrice === null || subService.basePrice === undefined) {
    return 'Sur demande';
  }
  if (subService.basePrice === 0) {
    return 'Gratuit';
  }
  return `${subService.basePrice} ${subService.currency}`;
}

/**
 * Vérifie si un service est gratuit pour les étudiants
 */
